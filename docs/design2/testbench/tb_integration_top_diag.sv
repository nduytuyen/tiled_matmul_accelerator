      elapsed_cycles += POLL_INTERVAL;
      axil_read(REG_AP_CTRL, ap_ctrl_val);
      $display("[DEBUG-DIAG] t=%0t cyc=%0d ap_ctrl=%b | gmemB AR=%b/%b addr=%0d R=%b qB=%0d | gmemC AW=%b/%b | tile_valid_o=%b tile_ready_o=%b tile_done_o=%b",
                $time, elapsed_cycles, ap_ctrl_val[3:0],
                m_axi_gmemB_ARVALID, m_axi_gmemB_ARREADY, m_axi_gmemB_ARADDR, m_axi_gmemB_RVALID,
                ar_queue_gmemB.size(),
                m_axi_gmemC_AWVALID, m_axi_gmemC_AWREADY,
                tile_valid_o, tile_ready_o, tile_done_o);
      if (ap_ctrl_val[1]) begin
        $display("[TB-DIAG] ap_done=1 sau ~%0d cycle (t=%0t)", elapsed_cycles, $time);
        break;
      end
      if (elapsed_cycles >= WATCHDOG_CYCLES) begin
        timed_out = 1'b1;
        break;
      end
    end

    if (timed_out) begin
      $display("[FAIL-DIAG] TIMEOUT -- van treo du da bo copy_A_banks. Nghi van cua Design SAI");
      $display("[FAIL-DIAG] (khong phai loi ranh gioi FSM) -- loi nam trong chinh copy_B_block.");
    end else begin
      $display("[PASS-DIAG] AP_DONE len 1 -- copy_B_block CHAY DUOC khi khong co copy_A_banks.");
      $display("[PASS-DIAG] Xac nhan dung nghi van cua Design (loi o ranh gioi chuyen tiep FSM).");
    end

    $display("========================================");
    $display("tb_integration_top_diag: ket thuc (%s)", timed_out ? "TIMEOUT" : "AP_DONE");
    $display("========================================");

    $finish;
  end

