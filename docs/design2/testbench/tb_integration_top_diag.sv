      @(posedge ap_clk);
      if (s_axi_control_ARVALID && s_axi_control_ARREADY) begin
        s_axi_control_ARVALID = 1'b0;
        ar_done = 1'b1;
      end
    end
    while (!s_axi_control_RVALID) @(posedge ap_clk);
    data = s_axi_control_RDATA;
    s_axi_control_RREADY = 1'b0;
  endtask


